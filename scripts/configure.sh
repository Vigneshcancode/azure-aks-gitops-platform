#!/usr/bin/env bash
# Writes the Azure values the GitOps layer needs and points ArgoCD at your repo.
# Run after the first successful terraform-apply for the environment, then commit and push.
#
#   GITHUB_REPO=owner/repo ./scripts/configure.sh dev
set -euo pipefail

: "${GITHUB_REPO:?Set GITHUB_REPO=owner/repo}"
ENVIRONMENT="${1:-dev}"
PROJECT="${PROJECT:-aksgitops}"
RG="rg-${PROJECT}-${ENVIRONMENT}"
REPO_URL="https://github.com/${GITHUB_REPO}.git"

cd "$(dirname "$0")/.."

ACR_LOGIN="$(az acr list -g "$RG" --query "[0].loginServer" -o tsv)"
KV_NAME="$(az keyvault list -g "$RG" --query "[0].name" -o tsv)"
CLIENT_ID="$(az identity show -g "$RG" -n "id-${PROJECT}-${ENVIRONMENT}-hello-api" --query clientId -o tsv)"
TENANT_ID="$(az account show --query tenantId -o tsv)"

for v in ACR_LOGIN KV_NAME CLIENT_ID TENANT_ID; do
  if [ -z "${!v}" ]; then
    echo "Could not resolve $v. Has terraform-apply for '$ENVIRONMENT' finished?" >&2
    exit 1
  fi
done

VALUES="helm/hello-api/values-${ENVIRONMENT}.yaml"
CURRENT_TAG="$(grep -E '^  tag:' "$VALUES" 2>/dev/null | sed -E 's/.*"(.*)".*/\1/' || true)"
CURRENT_TAG="${CURRENT_TAG:-pending}"

cat > "$VALUES" <<YAML
# Environment values for ${ENVIRONMENT}.
# Generated by scripts/configure.sh; the app-ci workflow updates image.tag.
image:
  repository: ${ACR_LOGIN}/hello-api
  tag: "${CURRENT_TAG}"

workloadIdentity:
  clientId: ${CLIENT_ID}

keyVault:
  name: ${KV_NAME}
  tenantId: ${TENANT_ID}
YAML

sed -i "s|REPO_URL_PLACEHOLDER|${REPO_URL}|g" gitops/argocd/root-app.yaml gitops/apps/hello-api.yaml

echo "Wrote $VALUES and set repoURL to $REPO_URL"
echo "Next: git add -A && git commit -m 'chore: configure ${ENVIRONMENT}' && git push"
